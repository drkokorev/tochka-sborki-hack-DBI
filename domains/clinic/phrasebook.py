def _expand(cores: list[str], fill: list[str]) -> list[str]:
    return [c.replace("{x}", f) for c in cores for f in fill]


def build() -> dict[str, str]:
    """Шаблон → речевой акт. Строится один раз при загрузке модуля."""
    table: dict[str, str] = {}

    def add(phrases, act: str) -> None:
        for p in phrases:
            key = " ".join(_DROP.sub(" ", p).split())
            if key:
                table.setdefault(key, act)

    book = _expand(_BOOK_CORE, ["{spec}", "{doc}"]) + _BOOK_GENERIC
    book += [f"да {b}" for b in book] + [f"а {b}" for b in _BOOK_GENERIC]
    add((" ".join(f"{b} {w}".split()) for b, w in product(book, _WHEN)), "intent:book")
    add((" ".join(f"{r} {w}".split()) for r, w in product(_RESCHEDULE, ["", "на {day}", "на {date}", "на другой день",
                                                                         "на другое время", "на {day} в {time}"])),
        "intent:reschedule")
    add((" ".join(f"{c} {w}".split()) for c, w in product(_CANCEL, ["", "на {day}", "на {date}", "на {day} в {time}"])),
        "intent:cancel")
    add(_STATUS, "intent:status")
    add(_expand(_SCHEDULE, ["{spec}", "{doc}", "доктор {doc}", "врач {doc}"]), "intent:schedule")
    add(_YES + [f"{y} спасибо" for y in _YES], "yes")
    add(_NO, "no")
    add(_BYE, "bye")
    add(_SMALLTALK, "smalltalk")
    add(_CHOICE, "choice")
    slot_words = ["{day}", "на {day}", "в {day}", "во {day}", "{date}", "на {date}", "в {time}", "на {time}", "в {num}",
                  "на {num}", "{day} в {time}", "{day} в {num}", "на {day} в {time}", "в {day} в {time}",
                  "во {day} в {time}", "после {num}", "до {num}", "утром", "вечером", "после обеда", "с утра",
                  "на {day} утром", "на {day} после обеда", "на {day} вечером", "к {doc}", "к другому врачу",
                  "на следующей неделе", "в {day} утром", "во {day} утром", "в {day} после обеда",
                  "во {day} после обеда", "в {day} вечером", "во {day} вечером", "{time}", "в {num} часов",
                  "на {num} часов"]
    add((s.replace("{w}", w) for s, w in product(_SLOTS, slot_words)), "slots")
    add(_HUMAN + [f"{h} пожалуйста" for h in _HUMAN], "flag:human")
    for key, phrases in _FAQ.items():
        add(phrases, f"faq:{key}")
    return table


TABLE = build()


def covered_phrases() -> int:
    """Сколько конкретных фраз покрывает словарь: каждый шаблон раскрывается по числу значений в нём."""
    values = {"{spec}": 40, "{doc}": 80, "{day}": 9, "{date}": 60, "{time}": 24, "{num}": 12}
    total = 0
    for key in TABLE:
        n = 1
        for ph, v in values.items():
            n *= v ** key.count(ph)
        total += n
    return total


def lookup(text: str, speech: SpeechNormalizer | None = None, find_doctor=None) -> str | None:
    """Речевой акт для стандартной фразы или None."""
    key = skeleton(text, speech, find_doctor)
    if not key:  # «Здравствуйте!», «Алло, добрый день» — только приветствие
        return "smalltalk" if re.search(r"[а-яa-z]", text.lower()) else None
    return TABLE.get(key)
