def act_fields(act: str) -> dict:
    """Поля ClinicUpdate, которые задаёт акт (остальное — от правил)."""
    kind, _, value = act.partition(":")
    if kind == "intent":
        return {"intent": value}
    if kind == "faq":
        return {"topic": value}
    if kind == "flag":
        return {"red_flag": value}
    if act == "yes":
        return {"confirm": True}
    if act == "no":
        return {"confirm": False}
    if act == "bye":
        return {"bye": True}
    if act == "smalltalk":
        return {"smalltalk": True}
    return {}
