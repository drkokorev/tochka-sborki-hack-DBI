def transfer_header(key: str) -> str:
    """Первая строка заявки на перевод в МИС: «ПЕРЕВОД R-02 P2» (лист ожидания — «ЛИСТ ОЖИДАНИЯ P3»)."""
    route = ROUTES.get(key) or ROUTES["human"]
    return f"ПЕРЕВОД {route.rule} {route.priority}" if route.rule else f"ЛИСТ ОЖИДАНИЯ {route.priority}"

