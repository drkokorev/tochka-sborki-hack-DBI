@dataclass(frozen=True)
class Route:
    phrase: str        # что говорим пациенту
    ask_card: bool     # один раз попросить ФИО и дату рождения для карточки перевода
    label: str         # заголовок карточки (описание эскалации в МИС)
    rule: str = ""     # правило матрицы маршрутизации (регламент 7.3)
    priority: str = "P3"  # приоритет очереди (регламент 7.5): P1 — немедленно, P2 — до 30 с, P3 — до 90 с
    outcome: str = "ESCALATED"  # код итога: ESCALATED — соединили с сотрудником, CALLBACK — задача на обратный звонок


