def faq_topic(text: str) -> str | None:
    """Тема справочного вопроса по правилам; text — в нижнем регистре, «ё» → «е»."""
    return next((f.key for f in FAQS if re.search(f.pattern, text)), None)


def faq_answer(key: str, text: str) -> tuple[str, str | None]:
    """Ответ и специальность для предложения записи (None — не предлагать, "" — спросить специальность)."""
    faq = FAQ_BY_KEY[key]
    text = text.lower().replace("ё", "е")
    if faq.answer == "PRICE":
        for pattern, service, price, offer in PRICES:
            if re.search(pattern, text):
                return f"{service} стоит {price} рублей.", offer or ""
        return "Цены на платные услуги подскажет платное отделение, добавочный три. Назовите услугу, если хотите.", None
    if faq.answer == "LAB":
        for pattern, name, days in LAB_TIMES:
            if re.search(pattern, text):
                return f"{name}: срок готовности — {days}. {_LAB_WHERE}", None
        return ("Общий анализ крови готов за один рабочий день, биохимия — за один или два, гормоны — "
                "от трёх до пяти рабочих дней. " + _LAB_WHERE), None
    return faq.answer, faq.offer


def topics_hint() -> str:
    return "; ".join(f"{f.key} — {f.hint}" for f in FAQS)
